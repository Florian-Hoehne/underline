//! Generates the Tauri context and the permissions of the app's own commands
//! (`allow-<command>`), which `capabilities/main.json` grants to the window.

fn main() {
    let manifest = tauri_build::AppManifest::new().commands(&[
        "app_start",
        "settings_quick",
        "wiki_check",
        "ws_start",
        "ws_recent",
        "ws_open",
        "ws_check_new",
        "ws_create",
        "tab_open",
        "tab_activate",
        "tab_close",
        "tab_store",
        "tab_set_view",
        "ed_viewport",
        "ed_sync",
        "ed_resync",
        "ed_mirror",
        "app_request_close",
        "clip_read_text",
        "clip_write_text",
        "clip_read",
        "clip_write",
        "clip_store_image",
        "clip_forget",
        "ed_embed",
        "ed_drop",
        "ed_drag",
        "ed_note_link",
        "ed_follow_link",
        "link_open_web",
        "app_close_anyway",
        "note_new_start",
        "note_plan",
        "note_create",
        "note_rename_start",
        "note_plan_rename",
        "note_rename",
        "note_delete_start",
        "note_delete",
        "note_undo_delete",
        "ws_restore",
        "ws_restore_as",
        "ws_purge",
        "search_set",
        "search_page",
        "search_open",
    ]);
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest))
        .expect("the Tauri build script failed");
}
